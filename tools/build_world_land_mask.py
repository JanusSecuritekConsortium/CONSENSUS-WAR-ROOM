"""Build core/intelligence/world_land_mask.py from a Natural Earth land GeoJSON file.

Run once by hand; the app never downloads map data itself:

    python tools/build_world_land_mask.py path/to/ne_110m_land.geojson

Natural Earth (naturalearthdata.com) is public domain. The mask has one character per 1 degree
cell: row 0 is latitude 89.5, column 0 is longitude -179.5, "#" is land and "." is sea.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import List, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "core" / "intelligence" / "world_land_mask.py"
Ring = Sequence[Tuple[float, float]]


def _rings(geometry: dict) -> List[List[Ring]]:
    """Each polygon as [outer ring, holes...]."""
    if geometry.get("type") == "Polygon":
        return [geometry["coordinates"]]
    if geometry.get("type") == "MultiPolygon":
        return list(geometry["coordinates"])
    return []


def _inside(lon: float, lat: float, ring: Ring) -> bool:
    inside = False
    count = len(ring)
    j = count - 1
    for i in range(count):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def build_rows(geojson: dict) -> List[str]:
    polygons = []
    for feature in geojson.get("features", []):
        for polygon in _rings(feature.get("geometry") or {}):
            outer = polygon[0]
            lons = [point[0] for point in outer]
            lats = [point[1] for point in outer]
            polygons.append(((min(lons), max(lons), min(lats), max(lats)), polygon))
    rows = []
    for row in range(180):
        lat = 89.5 - row
        cells = []
        for column in range(360):
            lon = -179.5 + column
            land = False
            for (lon_min, lon_max, lat_min, lat_max), polygon in polygons:
                if not (lon_min <= lon <= lon_max and lat_min <= lat <= lat_max):
                    continue
                if _inside(lon, lat, polygon[0]) and not any(_inside(lon, lat, hole) for hole in polygon[1:]):
                    land = True
                    break
            cells.append("#" if land else ".")
        rows.append("".join(cells))
    return rows


def render_module(rows: List[str]) -> str:
    body = "\n".join(f'    "{row}",' for row in rows)
    return (
        '"""1 degree land mask generated by tools/build_world_land_mask.py from Natural Earth 1:110m land\n'
        "(public domain). Row 0 is latitude 89.5, column 0 is longitude -179.5; '#' is land. Do not edit by hand.\n"
        '"""\n'
        "LAND_MASK = (\n"
        f"{body}\n"
        ")\n"
    )


def main(argv: List[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    geojson = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    TARGET.write_text(render_module(build_rows(geojson)), encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
